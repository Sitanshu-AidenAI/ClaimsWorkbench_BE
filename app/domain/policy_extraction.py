#: A US ZIP or a UK postcode, and the context that proves it is one.
#:
#: A bare `\d{5}` is the single worst pattern this module could carry: a
#: declarations page is full of five-digit numbers that are not postcodes — the
#: carrier's NAIC number, a producer code, half a policy number, a NAICS code —
#: and every one of them would become a location token that some notice eventually
#: collides with. So a US ZIP is only a ZIP when a two-letter state code precedes
#: it, which is how an address is written and how none of the others are.
_POSTCODE_RE = re.compile(
    r"(?:\b[A-Z]{2}\s+(?P<zip>\d{5}(?:-\d{4})?)\b"
    # The space between the outward and inward halves is required rather than
    # optional. Without it `PC290LC` — a plant serial number on an equipment
    # schedule — parses as a valid UK postcode and becomes a location token that
    # some future notice collides with.
    r"|\b(?P<uk>[A-Z]{1,2}\d[A-Z\d]?\s\d[A-Z]{2})\b)"
)

#: A money amount with its currency mark. Only used for display on the card.
_AMOUNT_RE = re.compile(r"[$£€]\s?[\d,]{4,}(?:\.\d{2})?")

#: Words that mean a line is a heading rather than a value, when a label's value
#: wrapped onto the next line.
_STOP_LINE_RE = re.compile(r"^[A-Z][A-Z \-/&]{6,}:?\s*$")

#: A class of insureds rather than a party. Matches nothing and dilutes every
#: comparison it joins, so it is dropped from the joint names.
_CLASS_OF_INSUREDS_RE = re.compile(
    r"^(all |any )?(sub)?contractors?\b|^all \w+ of every tier", re.IGNORECASE
)

#: A corporate form. A joint name is required to carry one, which is the test that
#: separates a *party* from the prose around it in a scheduled block.
#:
#: The block is written as a list of entities, but an entry's qualifying clause wraps
#: onto the following lines — "…but only for their interest in materials, supplies," /
#: "equipment and temporary works forming part of the insured project" — and a
#: connective like "including but not limited to" sits between entries. Every one of
#: those would otherwise be stored as an insured and then compared against the notice's
#: insured name, where it can only ever dilute.
#:
#: The cost is a sole trader with no corporate form dropping out of the *joint* list.
#: Accepted deliberately: the first named insured is read separately and is unaffected,
#: and a commercial policy's joint names are companies.
_CORPORATE_FORM_RE = re.compile(
    r"\b(llc|l\.l\.c|llp|lp|l\.p|inc|incorporated|ltd|limited|plc|corp|corporation|"
    r"company|co|partners|partnership|holdings|group|trust|association|"
    r"gmbh|sarl|bv|nv|pty|sa)\b\.?$",
    re.IGNORECASE,
)

#: A scheduled list's entry marker: `1.`, `(2)`, `-`, `•`, `a)`.
_LIST_MARKER_RE = re.compile(r"^\s*(?:\(?\d{1,2}[).]|[a-z][).]|[-*\u2022])\s+")

#: The same, for an address line, and deliberately stricter: the marker's punctuation
#: is **required**. Without it the pattern also matches a street number, which is the
#: one token on the line worth keeping.
_MARKER_ONLY_RE = re.compile(r"^\s*(?:\(\d{1,2}\)|\d{1,2}[.)]|[a-z][.)]|[-*\u2022])\s+")


@dataclass(slots=True)
class PolicyFacts:
    """What a policy document says about itself.

    Six promoted fields plus a bag, mirroring `PolicyDocument`'s columns exactly, so
    the service that lands this has nothing to decide. `labels` records which label
    each value was read from — displayed on the Policies screen, because an
    administrator checking an ingestion needs to see *where* the number came from
    before trusting that it is the right one.
    """

    policy_number: str | None = None
    insured_name: str | None = None
    insurer_name: str | None = None
    broker_name: str | None = None
    policy_type: str | None = None
    line_of_business: LineOfBusiness | None = None
    effective_date: date | None = None
    expiry_date: date | None = None

    additional_insureds: list[str] = field(default_factory=list)
    postcodes: list[str] = field(default_factory=list)
    locations: list[str] = field(default_factory=list)
    limits: list[str] = field(default_factory=list)
    labels: dict[str, str] = field(default_factory=dict)

    @property
    def as_metadata(self) -> dict[str, Any]:
        """The JSON bag `PolicyDocument.extracted_metadata` holds."""
        return {
            "additional_insureds": self.additional_insureds,
            "postcodes": self.postcodes,
            "locations": self.locations,
            "limits": self.limits,
            "labels": self.labels,
        }

    @property
    def is_empty(self) -> bool:
        """Nothing identifying was read. A scan with no text layer looks like this."""
        return not any(
            (self.policy_number, self.insured_name, self.insurer_name, self.effective_date)
        )


def read_policy_facts(text: str, *, filename: str | None = None) -> PolicyFacts:
    """Read a policy document's declarations.

    `filename` is a *last* resort and only for the policy number, because the
    convention `POL-CP-4471-88210_Harborline….pdf` is real and useful and is still
    somebody's file-naming habit rather than the contract. A number read from the
    document always wins.
    """
    facts = PolicyFacts()
    if not text or not text.strip():
        return _with_filename_number(facts, filename)

    head = text[:DECLARATIONS_CHARACTERS]
    lines = head.splitlines()

    facts.policy_number, label = _labelled_reference(lines, _POLICY_NUMBER_LABELS)
    if label:
        facts.labels["policy_number"] = label

    facts.insured_name, label = _labelled_name(lines, _INSURED_LABELS)
    if label:
        facts.labels["insured_name"] = label
    #: The joint names underneath a scheduled `NAMED INSUREDS:` block. Held here rather
    #: than merged below, so an explicit `ADDITIONAL NAMED INSUREDS:` label still wins.
    joint = _joint_names(lines, _INSURED_LABELS)

    facts.insurer_name, label = _labelled_name(lines, _INSURER_LABELS)
    if facts.insurer_name is None:
        facts.insurer_name = _masthead_insurer(lines)
        label = "masthead" if facts.insurer_name else None
    if label:
        facts.labels["insurer_name"] = label

    facts.broker_name, label = _labelled_name(lines, _BROKER_LABELS)
    if label:
        facts.labels["broker_name"] = label

    facts.policy_type, label = _labelled_name(lines, _TYPE_LABELS)
    if facts.policy_type is None:
        facts.policy_type = _coverage_part_heading(lines)
        label = "heading" if facts.policy_type else None
    if label:
        facts.labels["policy_type"] = label

    facts.effective_date, facts.expiry_date = read_policy_period(head)
    facts.line_of_business = read_line_of_business(head, policy_number=facts.policy_number)

    facts.additional_insureds = _additional_insureds(lines) or joint
    #: Whose address is whose. Computed once and used for both, because a postcode
    #: read off the producer's line is as wrong as the producer's street is.
    foreign = _foreign_address_lines(lines)
    facts.postcodes = _postcodes(
        "\n".join(line for index, line in enumerate(lines) if index not in foreign)
    )
    facts.locations = _locations(lines, foreign)
    facts.limits = _limits(head)

    return _with_filename_number(facts, filename)


def read_policy_period(text: str) -> tuple[date | None, date | None]:
    """The term, from the `POLICY PERIOD` line if there is one.

    Scoped to that line rather than taken as the first two dates in the document,
    because a declarations page also carries an issue date, a retroactive date and
    an anniversary date — and "the first two dates" reads whichever pair the layout
    happened to put first.
    """
    found = _PERIOD_RE.search(text)
    body = found.group("body") if found else ""
    dates = _dates_in(body)
    if len(dates) >= 2:
        first, second = dates[0], dates[1]
        return (first, second) if second >= first else (second, first)

    # No period line. Two dates joined by `to`/`through` anywhere in the
    # declarations is the other form this is written in.
    span = re.search(
        r"(?P<from>[\w/\-, ]{6,24})\s+(?:to|through|until|-)\s+(?P<to>[\w/\-, ]{6,24})", text
    )
    if span:
        pair = _dates_in(span.group(0))
        if len(pair) >= 2:
            first, second = pair[0], pair[1]
            return (first, second) if second >= first else (second, first)

    single = dates[0] if dates else None
    return (single, None)


def read_line_of_business(text: str, *, policy_number: str | None = None) -> LineOfBusiness | None:
    """Which line this wording is, from its coverage phrases then its prefix.

    `None` rather than `UNKNOWN`, deliberately. `UNKNOWN` is a value a match could
    be *filtered* on, and filtering the library to policies whose line could not be
    determined is the opposite of what a caller wants; `None` means "do not filter
    on this", which is the honest instruction.
    """
    # Two windows, and within each the *earliest* phrase wins rather than the
    # highest-priority one. Both halves of that matter and both were bugs:
    #
    # * A property policy's declarations mention "course of construction" in a
    #   builder's-risk exclusion, so reading the whole page at once lets an
    #   exclusion decide the line — and a manufacturing property policy filed as
    #   construction is filtered out of every property notice's candidate set.
    # * A companion inland-marine floater names the CGL it sits beside. Ranking by
    #   a fixed order of lines makes whichever line happens to be listed first in
    #   `_LINE_PHRASES` win an argument that position settles correctly: a document
    #   says what it *is* in its heading and mentions what it is not underneath.
    for window in (text[:_HEADING_CHARACTERS].lower(), text.lower()):
        best: tuple[int, LineOfBusiness] | None = None
        for line, phrases in _LINE_PHRASES:
            for phrase in phrases:
                at = window.find(phrase)
                if at >= 0 and (best is None or at < best[0]):
                    best = (at, line)
        if best is not None:
            return best[1]

    prefix = (policy_number or "").strip().upper()
    head = re.match(r"([A-Z]{2,4})", prefix)
    if head:
        return _PREFIX_LINES.get(head.group(1))
    return None


# --- label readers ------------------------------------------------------------


def _label_value(lines: list[str], labels: tuple[str, ...]) -> tuple[str | None, str | None]:
    """The raw text following the first of `labels` that appears, and which it was.

    Handles the two shapes a declarations page uses: `LABEL: value` and a `LABEL:`
    whose value wrapped onto the following lines. A wrapped value stops at the next
    line that looks like a heading, which is what keeps `MAILING ADDRESS` out of the
    named insured.
    """
    for label in labels:
        # `NAMED INSUREDS (as their interests may appear):` is one label with a
        # parenthetical qualification, not a label followed by a value. Every
        # declarations page in the wild writes at least one of these.
        pattern = re.compile(
            rf"^\s*{re.escape(label)}s?\s*(?:\([^)]{{0,60}}\))?\s*:\s*(?P<rest>.*)$",
            re.IGNORECASE,
        )
        for index, line in enumerate(lines):
            found = pattern.match(line)
            if not found:
                continue
            rest = found.group("rest").strip()
            if rest:
                return rest, label
            # The value wrapped. Take the next non-empty line that is not itself a
            # heading; a `LABEL:` followed immediately by another `LABEL:` has no
            # value at all, and inventing one from the next label's text is worse
            # than reporting nothing.
            for following in lines[index + 1 : index + 4]:
                candidate = following.strip()
                if not candidate:
                    continue
                if _STOP_LINE_RE.match(candidate) or ":" in candidate[:24]:
                    break
                return candidate, label
            break
    return None, None


def _labelled_reference(lines: list[str], labels: tuple[str, ...]) -> tuple[str | None, str | None]:
    """A reference read from a label, refusing one the surrounding words disclaim."""
    raw, label = _label_value(lines, labels)
    if raw:
        found = _REFERENCE_RE.search(raw.upper())
        if found:
            return _tidy_reference(found.group(1)), label

    # No usable label. Fall back to the first reference in the declarations that is
    # not preceded by "renewal of" and friends.
    for line in lines:
        upper = line.upper()
        for found in _REFERENCE_RE.finditer(upper):
            before = line[: found.start()]
            if _DISCLAIMED_RE.search(before):
                continue
            if re.search(r"(naic|producer\s+code|form|sic|naics|zip)\D{0,6}$", before, re.I):
                continue
            return _tidy_reference(found.group(1)), "unlabelled"
    return None, None


def _labelled_name(lines: list[str], labels: tuple[str, ...]) -> tuple[str | None, str | None]:
    raw, label = _label_value(lines, labels)
    if not raw:
        return None, None
    return _tidy_name(raw), label


def _masthead_insurer(lines: list[str]) -> str | None:
    """The carrier from the top of the page, when no label names it.

    A declarations page opens with the carrier's name in capitals. Matched on the
    corporate form rather than on the capitalisation, because plenty of headings are
    also in capitals and only one of them says "Insurance Company".
    """
    for line in lines[:12]:
        candidate = line.strip()
        if not candidate or len(candidate) > 120:
            continue
        if re.search(
            r"\b(insurance company|assurance|underwriters|mutual|syndicate|"
            r"insurance exchange|specialty insurance|casualty)\b",
            candidate,
            re.IGNORECASE,
        ):
            return _tidy_name(candidate)
    return None


def _coverage_part_heading(lines: list[str]) -> str | None:
    """The `… COVERAGE PART` / `… POLICY` heading, as the document's own words."""
    for line in lines[:30]:
        candidate = line.strip(" -")
        if not candidate or len(candidate) > 120:
            continue
        # A heading has no colon. `POLICY NUMBER:  BR-6612-77309` is all-caps and
        # contains the word "policy", so without this it reads as the policy type
        # and the card shows "POLICY NUMBER" where the coverage part should be.
        if ":" in candidate:
            continue
        if re.search(
            r"\b(coverage part|coverage form|policy|floater|builders risk|"
            r"builder's risk|general liability|inland marine)\b",
            candidate,
            re.I,
        ) and (candidate.upper() == candidate):
            cleaned = re.split(r"\s+-\s+DECLARATIONS|\bDECLARATIONS\b", candidate)[0]
            tidy = _tidy_name(cleaned)
            if tidy and len(tidy) > 8:
                return tidy
    return None


def _is_party(name: str) -> bool:
    """Whether a line from a scheduled block names an entity.

    Three refusals, each for a shape the corpus actually contains: a class of insureds
    ("all subcontractors of every tier"), a clause continuation (starts lower-case, or
    carries no corporate form), and a connective ("including but not limited to").
    """
    if _CLASS_OF_INSUREDS_RE.match(name):
        return False
    if not name[:1].isupper():
        return False
    # A schedule annotates an entry with its role in brackets — `Sundale Residential
    # Management, LLC (Managing Agent)` — and the corporate-form test is anchored at the
    # end, so the annotation has to come off before the test rather than defeat it.
    body = re.sub(r"\s*\([^)]{0,60}\)\s*$", "", name).rstrip(" .,;")
    return bool(_CORPORATE_FORM_RE.search(body))


def _joint_names(lines: list[str], labels: tuple[str, ...]) -> list[str]:
    """The second and later entries of a scheduled block of named insureds.

    A construction policy does not write "additional named insureds". It writes

        NAMED INSUREDS (as their respective interests may appear):
            1.  Rivergate Development Partners, LLC ..... Project Owner / Developer
            2.  Vanterra Construction Group, LLC ........ General Contractor

    and every one of those is an insured. Reading only the first entry is the single
    most damaging omission this module could make on a construction risk, because the
    party reporting the loss is very often the contractor rather than the employer — so
    the insured signal scores a *mismatch* against the right policy and the confidence
    band is capped by rule.

    Returns every entry that is a party, minus the named insured itself when the block
    is where that name came from — see the comment on `insured_is_inline`.
    """
    for label in labels:
        pattern = re.compile(
            rf"^\s*{re.escape(label)}s?\s*(?:\([^)]{{0,60}}\))?\s*:\s*(?P<rest>.*)$",
            re.IGNORECASE,
        )
        for index, line in enumerate(lines):
            head = pattern.match(line)
            if not head:
                continue

            # Whether the label carried its value on its own line decides whether the
            # block's first entry is the named insured or already an additional one:
            #
            #     NAMED INSURED:  Fairmount Textile Mills Holdings, Inc.   <- inline
            #         including but not limited to:
            #         Fairmount Weaving Company, LLC                       <- additional
            #
            #     NAMED INSUREDS:                                          <- no value
            #         1. Rivergate Development Partners, LLC               <- the insured
            #         2. Vanterra Construction Group, LLC                  <- additional
            #
            # Getting this wrong silently deletes one real joint name per policy, which
            # is why it is read from the label line rather than assumed either way.
            insured_is_inline = bool(head.group("rest").strip())

            found: list[str] = []
            for following in lines[index + 1 : index + 14]:
                candidate = following.strip()
                if not candidate:
                    # A blank line ends the block. A scheduled list is contiguous, and
                    # reading past the gap collects the mailing address as an insured.
                    break
                if _STOP_LINE_RE.match(candidate) or ":" in candidate[:24]:
                    break
                name = _tidy_name(candidate)
                if name and _is_party(name):
                    found.append(name)

            ordered = list(dict.fromkeys(found))
            if insured_is_inline:
                return ordered
            # The first entry is the named insured, already read by `_labelled_name`.
            # Returning it here too would let one name match itself.
            return ordered[1:]
    return []


def _additional_insureds(lines: list[str]) -> list[str]:
    """The parties insured besides the first named one.

    Read because a commercial loss is very often reported by one of them: a joint
    venture partner, a subsidiary, a leasing entity. A matcher that compares a
    notice's insured name only against the *first* named insured scores a mismatch
    against the right policy, which is the error this list exists to prevent.
    """
    found: list[str] = []
    pattern = re.compile(
        r"^\s*(additional named insureds?|other named insureds?|also insured)\s*:\s*(?P<rest>.*)$",
        re.IGNORECASE,
    )
    for index, line in enumerate(lines):
        head = pattern.match(line)
        if not head:
            continue
        first = _tidy_name(head.group("rest"))
        if first:
            found.append(first)
        for following in lines[index + 1 : index + 12]:
            candidate = following.strip()
            if not candidate or _STOP_LINE_RE.match(candidate) or ":" in candidate[:24]:
                break
            tidy = _tidy_name(candidate)
            if tidy:
                found.append(tidy)
        break
    return list(dict.fromkeys(name for name in found if name))


def _declarations_start(lines: list[str]) -> int:
    """The first line of the declarations proper — the `POLICY NUMBER` line.

    Everything above it is the masthead: the carrier's name, its office address, its
    NAIC number and the program title. A premises schedule never appears there, and
    the carrier's own address always does.

    Returns 0 when no policy-number label can be found, which blocks nothing. That is
    the deliberate direction to fail in: a page this reader cannot navigate keeps the
    behaviour it had before, rather than having its first six lines discarded on a
    guess about a layout nobody has seen.
    """
    for label in _POLICY_NUMBER_LABELS:
        pattern = re.compile(rf"^\s*{re.escape(label)}s?\s*:", re.IGNORECASE)
        for index, line in enumerate(lines):
            if pattern.match(line):
                return index
    return 0


def _foreign_address_lines(lines: list[str]) -> set[int]:
    """Line indices whose address belongs to a party other than the insured.

    Two regions, both of which were reaching the premises schedule:

    * **The masthead**, above the policy number — the carrier's own office.
    * **A party block**: a `PRODUCER:` or `MORTGAGEE:` label and the indented
      continuation lines under it. Indentation is the boundary because it is what a
      declarations page actually uses to say "still the same party"; a label at the
      margin starts a new one.
    """
    blocked = set(range(_declarations_start(lines)))

    index = _declarations_start(lines)
    while index < len(lines):
        line = lines[index]
        if _is_foreign_label(line):
            blocked.add(index)
            index += 1
            while index < len(lines):
                following = lines[index]
                if not following.strip() or not following[:1].isspace():
                    break
                blocked.add(index)
                index += 1
            continue
        index += 1
    return blocked


def _is_foreign_label(line: str) -> bool:
    """Whether a line labels a party whose address is not a premises."""
    return any(
        re.match(
            rf"^\s*{re.escape(label)}s?\s*(?:\([^)]{{0,60}}\))?\s*:",
            line,
            re.IGNORECASE,
        )
        for label in _FOREIGN_ADDRESS_LABELS
    )


def _postcodes(text: str) -> list[str]:
    """Every postcode in the declarations, deduplicated in document order.

    A list rather than one value because a policy schedules many premises, and the
    one that matters is whichever the loss happened at. Order is preserved so the
    first is the insured's mailing address, which is the one a card shows — which is
    true only because the caller has already removed the carrier's and the producer's
    own lines. Scanned over the whole declarations text before that, the first
    postcode was the carrier's head office.
    """
    seen: list[str] = []
    for found in _POSTCODE_RE.finditer(text):
        raw = found.group("zip") or found.group("uk") or ""
        value = re.sub(r"\s+", " ", raw.strip().upper())
        if value and value not in seen:
            seen.append(value)
        if len(seen) >= 40:
            break
    return seen


def _locations(lines: list[str], excluded: set[int] | None = None) -> list[str]:
    """Address-looking lines, for display on the card and for token overlap.

    A line is an address if it carries a postcode and a street number. Deliberately
    crude: this is not a geocoder, it is the material a location-overlap score is
    computed over, and a line that is not an address contributes tokens that no
    notice will match.

    `excluded` names the lines whose address belongs to somebody other than the
    insured — see `_foreign_address_lines`. An address is only a premises of *this*
    risk if it is the insured's.
    """
    excluded = excluded or set()
    found: list[str] = []
    for index, line in enumerate(lines):
        if index in excluded:
            continue
        candidate = re.sub(r"\s{2,}", " ", line.strip())
        if not (8 <= len(candidate) <= 200):
            continue

        street = bool(re.search(r"\b\d{1,6}\b\s+\w", candidate))
        postcode = bool(_POSTCODE_RE.search(candidate))

        # A declarations page wraps a mailing address over two lines: the street on
        # one and the town, state and ZIP on the next. Neither half is an address on
        # its own — the first has no postcode and the second has no street number — so
        # a per-line test collected nothing at all for the most common layout there is.
        if street and not postcode:
            after = index + 1
            following = (
                re.sub(r"\s{2,}", " ", lines[after].strip())
                if (after < len(lines) and after not in excluded)
                else ""
            )
            if _POSTCODE_RE.search(following) and not re.search(r"\b\d{1,6}\b\s+\w", following):
                candidate = f"{candidate}, {following}"
                postcode = True

        if not (street and postcode):
            continue

        cleaned = _tidy_address(candidate)
        if cleaned and cleaned not in found:
            found.append(cleaned)
        if len(found) >= 30:
            break
    return found


def _tidy_address(line: str) -> str:
    """One address line, with the page furniture around it removed.

    Three trims, and the first one is a bug fix rather than a nicety:

    * A **list marker** only — `(1)`, `2.` — never a bare leading number. The obvious
      pattern for a marker is "digits then space", and that is also what a street
      number is: it turned `2600 North Central Avenue` into `North Central Avenue` and
      quietly deleted the most discriminating token the line carried.
    * A **label prefix**, so `PROJECT ADDRESS: 14900 South Cypress Landing Way` is
      stored as the address rather than as a sentence about one.
    * A **pipe-separated tail**, which is where a declarations page puts the NAIC
      number and the producer code beside an address. Those are digits that no notice
      will ever match, and every one of them dilutes the overlap score.
    """
    body = _MARKER_ONLY_RE.sub("", line.strip())
    body = re.sub(r"^[A-Z][A-Z /&-]{3,30}:\s*", "", body)
    body = body.split(" | ")[0]
    return re.sub(r"\s{2,}", " ", body).strip(" ,;-")


def _limits(text: str) -> list[str]:
    """The money amounts on the declarations, largest first, capped.

    Display only, and stated as such: nothing scores on these. A policy's headline
    limit is a fact an officer wants on the card, and reading it from the text is
    the only way to have it for a document that is not linked to a book row.
    """
    amounts = {re.sub(r"\s+", "", value) for value in _AMOUNT_RE.findall(text)}
    ordered = sorted(amounts, key=_amount_value, reverse=True)
    return ordered[:6]


def _amount_value(value: str) -> float:
    digits = re.sub(r"[^\d.]", "", value)
    try:
        return float(digits)
    except ValueError:
        return 0.0



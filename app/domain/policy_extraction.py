def _dates_in(text: str) -> list[date]:
    """Every date in `text`, in the order they appear, by the first pattern that hits.

    One pattern wins for the whole string rather than merging all four, because
    `03/01/2025` matches the slash pattern and `1 March 2025` matches the name
    pattern, and a document uses one convention throughout. Merging them would
    double-count and reorder.
    """
    for pattern, order in _DATE_PATTERNS:
        matches = list(pattern.finditer(text))
        if not matches:
            continue
        found: list[date] = []
        for match in matches:
            parsed = _to_date(match.groups(), order)
            if parsed is not None:
                found.append(parsed)
        if found:
            return found
    return []


def _to_date(groups: tuple[str, ...], order: tuple[str, ...]) -> date | None:
    parts: dict[str, str] = dict(zip(order, groups, strict=True))
    try:
        year = int(parts["year"])
        if "monthname" in parts:
            month = _MONTHS.get(parts["monthname"][:3].lower(), 0)
        else:
            month = int(parts["month"])
        day = int(parts["day"])
        if not month:
            return None
        return date(year, month, day)
    except (KeyError, ValueError):
        return None


def _tidy_reference(value: str) -> str:
    """A reference in the form the document printed it, with spacing normalised.

    Spacing only. The punctuation is *not* stripped here: this value is displayed
    and stored as the document's own rendering, and comparison goes through
    `normalise_reference`, which strips punctuation at the point of comparison
    rather than at the point of reading.
    """
    return re.sub(r"\s+", "", value.strip().upper()).strip("-/")


def _tidy_name(value: str) -> str | None:
    """A party name with its trailing noise removed.

    Declarations pages put a phone number, an email or a producer code on the same
    line as a name, separated by two or more spaces or a pipe. Cut on those rather
    than on the first comma, which would truncate "Kestrel Ridge Holdings, LP".
    """
    if not value:
        return None
    # A scheduled list numbers its entries — `1.  Rivergate Development Partners,
    # LLC ....` — and the marker has to go before the split, or the split takes
    # "1." as the whole name and the reader reports no insured at all.
    body = _LIST_MARKER_RE.sub("", value.strip())

    # Cut on the three things a declarations page puts after a name on the same
    # line: a run of spaces, a pipe, and the dot leaders a scheduled list uses to
    # align a role against it — `Halcyon Builders, LLC ...... General Contractor`.
    #
    # The trailing strip keeps `.`, because `Inc.` and `Co.` end in one and a name
    # stored as `Ironbark Constructors, Inc` is a name that no longer matches the
    # book. The dot leaders are already gone, cut by the split above.
    head = re.split(r"\s{2,}|\s\|\s|\t|\s\.{2,}", body)[0].strip(" ,;:-")
    head = re.sub(r"\s+", " ", head)
    if len(head) < 3 or len(head) > 200:
        return None
    if head.upper() in {"N/A", "NONE", "TBC", "TBD"}:
        return None
    return head


def _with_filename_number(facts: PolicyFacts, filename: str | None) -> PolicyFacts:
    """Fill a missing policy number from the filename, and say that is where it came from."""
    if facts.policy_number or not filename:
        return facts

    stem = re.sub(r"\.[A-Za-z0-9]{1,5}$", "", filename)
    for part in re.split(r"[_\s]+", stem.upper()):
        found = _REFERENCE_RE.fullmatch(part.strip("-")) or _REFERENCE_RE.search(part)
        if found:
            candidate = _tidy_reference(found.group(1))
            # `POL-CP-4471-88210` carries a scheme prefix the document does not.
            candidate = re.sub(r"^(POL|POLICY)-", "", candidate)
            if len(candidate) >= 5:
                facts.policy_number = candidate
                facts.labels["policy_number"] = "filename"
                return facts
    return facts


